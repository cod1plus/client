#!/usr/bin/env python3
"""
gen_lan_assets.py - packs assets/lan/ into src/ui/lan_assets.h for the streamer overlay (LAN look):

  fonts/*.ttf     the overlay's faces (OFL: Big Shoulders, Big Shoulders Stencil, Barlow Semi
                  Condensed), static instances renamed LanDisplay / LanDisplayBlack / LanStencil /
                  LanBody / LanBodyBold (codps3/streamer_lan/make_fonts.py). Registered in the
                  process only (AddFontMemResourceEx): nothing is installed on the player's PC.
  weapons/*.png   white weapon silhouettes rendered from the game's own 3D world models
                  (codps3/streamer_lan/weapon_icons.py, 10 px per game unit, muzzle right).

    python tools/gen_lan_assets.py        (run from the repository root)
"""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'assets', 'lan')
OUT = os.path.join(ROOT, 'src', 'ui', 'lan_assets.h')


def c_bytes(name, data):
    lines = []
    for i in range(0, len(data), 24):
        lines.append('    ' + ','.join('0x%02x' % b for b in data[i:i + 24]) + ',')
    return 'static const unsigned char %s[%d] = {\n%s\n};\n' % (name, len(data), '\n'.join(lines))


def ident(s):
    return ''.join(c if c.isalnum() else '_' for c in s)


def main():
    out = ['// GENERATED by tools/gen_lan_assets.py from assets/lan/ - do not edit',
           '#pragma once', '', 'namespace patches {', 'namespace lan_assets {', '',
           'struct Blob { const char* name; const unsigned char* data; int size; };', '']
    fonts = sorted(f for f in os.listdir(os.path.join(SRC, 'fonts')) if f.endswith('.ttf'))
    weapons = sorted(f for f in os.listdir(os.path.join(SRC, 'weapons')) if f.endswith('.png'))
    for f in fonts:
        out.append(c_bytes('font_' + ident(f[:-4]), open(os.path.join(SRC, 'fonts', f), 'rb').read()))
    for f in weapons:
        out.append(c_bytes('weapon_' + ident(f[:-4]), open(os.path.join(SRC, 'weapons', f), 'rb').read()))
    out.append('static const Blob k_fonts[] = {')
    for f in fonts:
        out.append('    { "%s", font_%s, (int)sizeof(font_%s) },' % (f[:-4], ident(f[:-4]), ident(f[:-4])))
    out.append('};')
    out.append('// weapon name without "_mp", lower case -> PNG')
    out.append('static const Blob k_weapons[] = {')
    for f in weapons:
        out.append('    { "%s", weapon_%s, (int)sizeof(weapon_%s) },' % (f[:-4].lower(), ident(f[:-4]), ident(f[:-4])))
    out.append('};')
    out += ['', '}  // namespace lan_assets', '}  // namespace patches', '']
    open(OUT, 'w', newline='\n').write('\n'.join(out))
    print(OUT, os.path.getsize(OUT), 'bytes,', len(fonts), 'fonts,', len(weapons), 'weapons')


if __name__ == '__main__':
    main()
